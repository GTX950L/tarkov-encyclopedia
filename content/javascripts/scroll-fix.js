/* ==========================================================================
   导航后回到页面顶部（兜底）
   --------------------------------------------------------------------------
   背景：站点启用了 Material 的 navigation.instant（XHR 换页，不整页刷新）。
   它的滚动复位是间歇性的——同一站点、同样操作，实测有时归零、有时保留
   上一页的滚动位置（读者从长页面点左侧导航，会停在半中间）。

   这里在每次页面切换完成后兜底复位一次。document$ 是 Material 提供的
   observable，在首次加载与每次 instant 切换后都会触发。

   带锚点的跳转（#xxx）不处理——那是读者主动要求跳到某处，复位会打断它。
   ========================================================================== */

document$.subscribe(function () {
  if (!window.location.hash) {
    window.scrollTo({ top: 0, left: 0, behavior: "instant" });
  }
});

/* --------------------------------------------------------------------------
   第二层兜底：关掉浏览器的自动滚动恢复
   --------------------------------------------------------------------------
   只有上面那一次复位是不够的。浏览器的 history.scrollRestoration 默认是
   "auto"：它会在我们复位**之后**把上一页的滚动位置还回来——于是读者点完
   左侧导航，仍然停在半中间。实测（整页加载长条目 → 滚到 2500px → 点侧栏）：
   开着 auto 时 scrollY 原样保留 2500，稳定复现；改成 manual 后才真正归零。

   注意两件事：
     1. 必须放在 document$ 订阅**之外/之后都行**，但要早于第一次导航；
     2. 它不影响带锚点的跳转（#xxx）——那由上面的 hash 判断继续放行。
   -------------------------------------------------------------------------- */
if ("scrollRestoration" in history) {
  history.scrollRestoration = "manual";
}

/* --------------------------------------------------------------------------
   第三层：点击导航链接的**那一刻**就先复位
   --------------------------------------------------------------------------
   只靠 document$ 复位有一个体感问题：它要等新页面的内容（XHR）就绪才触发，
   弱网下会明显滞后——实测同一操作有时 80ms 归零、有时要等 500–1000ms，
   读者看到的是「停在半中间顿一下，再跳回顶部」。

   所以这里在点下去的瞬间先复位一次（内容到达后再由 document$ 兜第二次）。

   两条放行规则：
     1. 带锚点的链接（#xxx）不处理——那是读者主动要求跳到某处；
     2. **站外**链接不处理——不是站内换页。

   ⚠️ 第 2 条不能用「href 以 http 开头」来判断：Material 构建后，站内导航链接
   的 href 是**绝对 URL**（https://…/entries/bosses/），那一刀会**把所有站内
   链接都误判成外链**，这一层就形同虚设（本站踩过）。必须用 origin 比对。
-------------------------------------------------------------------------- */
document.addEventListener("click", function (e) {
  var a = e.target && e.target.closest ? e.target.closest("a[href]") : null;
  if (!a) return;
  var href = a.getAttribute("href") || "";
  if (!href) return;
  var url;
  try {
    url = new URL(a.href, location.href);
  } catch (err) {
    return;
  }
  if (url.origin !== location.origin) return;   // 站外：不管
  if (url.hash) return;                          // 带锚点：读者自己要跳到某处
  window.scrollTo({ top: 0, left: 0, behavior: "instant" });
}, true);
