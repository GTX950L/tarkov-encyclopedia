/* ==========================================================================
   导航后回到页面顶部（兜底）
   --------------------------------------------------------------------------
   背景：站点启用了 Material 的 navigation.instant（XHR 换页，不整页刷新）。
   它的滚动复位是间歇性的——同一站点、同样操作，实测有时归零、有时保留
   上一页的滚动位置（读者从长页面点左侧导航，会停在半中间）。

   这里在每次页面切换完成后兜底复位一次。document$ 是 Material 提供的
   observable，在首次加载与每次 instant 切换后都会触发。

   带锚点的跳转（#xxx）不处理——那是读者主动要求跳到某处，复位会打断它。
   ========================================================================== */

document$.subscribe(function () {
  if (!window.location.hash) {
    window.scrollTo({ top: 0, left: 0, behavior: "instant" });
  }
});
